// ---- deterministic history generator ----
function seeded(seed: number) {
  let s = seed % 2147483647
  if (s <= 0) s += 2147483646
  return () => (s = (s * 16807) % 2147483647) / 2147483647
}

const WEEKS = ['W1', 'W2', 'W3', 'W4', 'W5', 'W6', 'W7', 'W8', 'W9', 'Now']

function makeHistory(seed: number, start: number, end: number, vol: number): ValuePoint[] {
  const rand = seeded(seed)
  const n = WEEKS.length
  return WEEKS.map((week, i) => {
    const t = i / (n - 1)
    const base = start + (end - start) * t
    const noise = (rand() - 0.5) * 2 * vol
    const value = Math.max(1, Math.round((base + noise) * 10) / 10)
    return { week, value }
  })
}


// ---- derived collections for the Market dashboard ----
const byScoreDeltaDesc = (a: Player, b: Player) => b.scoreDelta - a.scoreDelta
const byValueDeltaDesc = (a: Player, b: Player) => b.valueDeltaPct - a.valueDeltaPct

export const marketRisers = [...players].sort(byValueDeltaDesc).slice(0, 5)
export const marketFallers = [...players].sort((a, b) => a.valueDeltaPct - b.valueDeltaPct).slice(0, 5)

export const buySignals = players
  .filter((p) => p.signal === 'STRONG BUY' || p.signal === 'BUY')
  .sort(byScoreDeltaDesc)
export const sellSignals = players.filter((p) => p.signal === 'SELL').sort((a, b) => a.scoreDelta - b.scoreDelta)
export const breakoutWatch = players.filter((p) => p.signal === 'BREAKOUT ALERT').sort(byScoreDeltaDesc)
export const roleChanges = players.filter((p) => p.signal === 'ROLE CHANGE').sort(byScoreDeltaDesc)
export const injuryOpportunities = players
  .filter((p) => p.signal === 'INJURY OPPORTUNITY')
  .sort(byScoreDeltaDesc)
export const waiverTargets = players
  .filter((p) => p.fantasyValue < 40 && p.trend === 'Rising')
  .sort(byValueDeltaDesc)
  .slice(0, 6)

